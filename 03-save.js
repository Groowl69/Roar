/* ============================================================
   03-save.js  ·  файл 6/16
   ------------------------------------------------------------
   Мета-прогресс: игровые слоты (п. 4.5), достижения, настройки.
   Хранится в localStorage и переживает забег.
   Данные самого забега (уровень, прокачка, инвентарь) — однора-
   зовые и живут только в состоянии G (п. 2.2), сюда не пишутся.
   ============================================================ */

const SAVE_KEY = 'oo78_meta_v1';

/* Мета-структура: три игровых слота (п. 4.5) + настройки.
   Каждый слот хранит: смерти, убийства, рекорд уровня, достижения. */
let meta = {
  slot: 0,                       // активный слот (0..2)
  slots: [
    { deaths: 0, kills: 0, best: 0, ach: [] },
    { deaths: 0, kills: 0, best: 0, ach: [] },
    { deaths: 0, kills: 0, best: 0, ach: [] }
  ],
  volM: 80,                      // общая громкость, 0..100
  volS: 80,                      // громкость эффектов, 0..100
  trapInd: true,                 // индикаторы ловушек вкл/выкл
  restartSeen: false             // игрок уже видел окно рестарта забега
};

/* Загрузка сохранений при старте. При повреждённом JSON молча
   играем на дефолтных значениях, чтобы не ронять запуск. */
try {
  const raw = localStorage.getItem(SAVE_KEY);
  if (raw) meta = Object.assign(meta, JSON.parse(raw));
} catch (e) { /* повреждённое сохранение — используем дефолт */ }

/* Записать текущий meta в localStorage. Обёрнуто в try/catch,
   чтобы не упасть, если хранилище переполнено или недоступно. */
function persist() {
  try { localStorage.setItem(SAVE_KEY, JSON.stringify(meta)); } catch (e) {}
}

/* Активный слот (объект с deaths/kills/best/ach) */
function slot() { return meta.slots[meta.slot]; }

/* Список достижений активного слота */
function curAch() { return meta.slots[meta.slot].ach; }

/* Выдать достижение активному слоту, если ещё не выдано.
   Возвращает true при первом получении. Тост и звук — здесь же,
   чтобы точки выдачи были однострочными. */
function grantAch(id) {
  if (curAch().indexOf(id) >= 0) return false;
  curAch().push(id);
  persist();
  const a = ACH.find(function (x) { return x.id === id; });
  achToast('Достижение: «' + (a ? a.n : id) + '»');
  SFX.ach();
  return true;
}

/* Стереть слот до начального состояния (п. 4.5). Вызывается из
   настроек после подтверждения с обратным 5-секундным отсчётом. */
function wipeSlot(i) {
  meta.slots[i] = { deaths: 0, kills: 0, best: 0, ach: [] };
  persist();
}

